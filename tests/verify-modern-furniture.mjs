import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const engine = require('../catalog-engine.js');
const target = process.argv[2];
if (!target) throw new Error('Uso: node tests/verify-modern-furniture.mjs <Modern Furniture BP.mcpack>');
const data = new Uint8Array(await fs.readFile(target));
const entries = await engine.flattenArchives([{ name: target.split('/').pop(), data }]);
const analysis = engine.analyzeEntries(entries, {});
const summary = analysis.report.summary;
assert.equal(summary.files, 1354);
assert.equal(summary.items, 7);
assert.equal(summary.blocks, 640);
assert.equal(summary.entities, 3);
assert.equal(summary.recipes, 606);
assert.equal(summary.acquisition, 3);
assert.equal(summary.errors, 0);
assert.equal(analysis.source.source.name, 'Modern Furniture');
assert.equal(analysis.source.source.id, 'modern_furniture');
assert.equal(analysis.source.source.author, 'Trotamundos872');
assert.equal(analysis.source.source.version, '13.7');
assert.equal(analysis.source.source.manifestVersion, '1.0.2');
assert.deepEqual(analysis.source.source.namespaces, ['f']);
assert.equal(analysis.source.source.license, 'Unknown / Not verified');
assert.equal(analysis.source.source.officialUrl, 'https://www.trmc-addons.com');
const duplicateWarnings = analysis.report.issues.filter(i => i.code === 'duplicate_content_equivalent');
assert.equal(duplicateWarnings.length, 14);
console.log('Modern Furniture: verificación completa aprobada.');
console.log(JSON.stringify(summary, null, 2));
