import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const engine = require('../catalog-engine.js');
const bp = process.argv[2];
const rp = process.argv[3];
if (!bp || !rp) throw new Error('Uso: node tests/verify-modern-furniture-bilingual.mjs <BP.mcpack> <RP.mcpack>');
const inputs = [];
for (const path of [bp, rp]) inputs.push({ name: path.split('/').pop(), data: new Uint8Array(await fs.readFile(path)) });
const entries = await engine.flattenArchives(inputs);
const analysis = engine.analyzeEntries(entries, { exportLocales: ['es_MX', 'en_US'], primaryLocale: 'es_MX' });
const summary = analysis.report.summary;
assert.equal(summary.files, 2303);
assert.equal(summary.items, 7);
assert.equal(summary.blocks, 640);
assert.equal(summary.entities, 3);
assert.equal(summary.recipes, 606);
assert.equal(summary.acquisition, 3);
assert.equal(summary.errors, 0);
assert.equal(summary.info, 1);
assert.deepEqual(summary.namesByLocale.es_MX, { localized: 627, generated: 23, manual: 0 });
assert.deepEqual(summary.namesByLocale.en_US, { localized: 633, generated: 17, manual: 0 });
const byId = new Map(analysis.content.items.map(entry => [entry.id, entry]));
assert.equal(byId.get('f:borrador').names.es_MX, 'Borrador de pizarra blanca');
assert.equal(byId.get('f:borrador').names.en_US, 'Draft whiteBoard');
assert.equal(byId.get('f:llave_inglesa').names.es_MX, 'Herramienta moderna');
assert.equal(byId.get('f:llave_inglesa').names.en_US, 'Modern Tool');
assert.equal(byId.get('f:manual').names.es_MX, 'Manual de Usuario [Interactivo]');
assert.equal(byId.get('f:manual').names.en_US, 'User Manual [Interactive]');
assert.equal(analysis.report.issues.filter(issue => issue.code === 'invalid_json').length, 0);
assert.equal(analysis.report.issues.filter(issue => issue.code === 'empty_optional_json_ignored').length, 1);

const exportedEntries = await engine.readZip(engine.exportContribution(analysis));
const readJson = name => JSON.parse(new TextDecoder().decode(exportedEntries.find(entry => entry.name === name).data));
const content = readJson('content.json');
const localization = readJson('localization.json');
assert.deepEqual(content.exportedLocales, ['es_MX', 'en_US']);
assert.deepEqual(Object.keys(content.items[0].names), ['es_MX', 'en_US']);
assert.deepEqual(Object.keys(localization.locales), ['es_MX', 'en_US']);

const englishOnly = engine.analyzeEntries(entries, { exportLocales: ['en_US'], primaryLocale: 'en_US' });
const englishZip = await engine.readZip(engine.exportContribution(englishOnly));
const englishContent = JSON.parse(new TextDecoder().decode(englishZip.find(entry => entry.name === 'content.json').data));
const englishLocalization = JSON.parse(new TextDecoder().decode(englishZip.find(entry => entry.name === 'localization.json').data));
assert.deepEqual(englishContent.exportedLocales, ['en_US']);
assert.deepEqual(Object.keys(englishContent.items[0].names), ['en_US']);
assert.deepEqual(Object.keys(englishLocalization.locales), ['en_US']);
assert.equal(englishContent.items[0].fallbackName, 'Draft whiteBoard');

const allEntries = [...analysis.content.items, ...analysis.content.blocks, ...analysis.content.entities];
const generated = allEntries.find(entry => entry.id === 'f:bladrillos_marron_blanco');
assert(generated, 'Debe existir el bloque generado de prueba');
assert.equal(generated.nameSources.es_MX, 'generated');
assert.equal(generated.names.es_MX, 'Bladrillos Marron Blanco');
generated.names.es_MX = 'Ladrillos marrón y blanco';
generated.nameSources.es_MX = 'manual';
generated.fallbackName = 'Ladrillos marrón y blanco';
generated.nameSource = 'manual';
const manualZip = await engine.readZip(engine.exportContribution(analysis));
const manualContent = JSON.parse(new TextDecoder().decode(manualZip.find(entry => entry.name === 'content.json').data));
const manualEntry = manualContent.blocks.find(entry => entry.id === 'f:bladrillos_marron_blanco');
assert.equal(manualEntry.names.es_MX, 'Ladrillos marrón y blanco');
assert.equal(manualEntry.nameSources.es_MX, 'manual');

console.log('Modern Furniture BP+RP: idiomas, limpieza, edición manual y exportación aprobados.');
console.log(JSON.stringify(summary, null, 2));
